using DependencyModules.SourceGenerator.Impl;
using DependencyModules.SourceGenerator.Impl.Models;
using DependencyModules.Tests.Infrastructure;
using Microsoft.CodeAnalysis;

namespace DependencyModules.Specs.GeneratorTests;

/// <summary>
/// The generator is configured through MSBuild properties surfaced as CompilerVisibleProperty in
/// the packaged build/*.targets. These tests pin the mapping from property value to generated code.
/// </summary>
public partial class ConfigurationTests
{
    [VerifyTest]
    public void ExcludeGeneratedCodeFromCoverage_DefaultsToOn()
    {
        var result = GeneratorTestHarness.Run(ModuleWithService);

        result.AssertNoErrors();
        Verify(result.SourceContaining("Dependencies").Contains("ExcludeFromCodeCoverage"));
    }

    [VerifyTest]
    public void ExcludeGeneratedCodeFromCoverage_False_OmitsTheAttribute()
    {
        var result = GeneratorTestHarness.Run(
            ModuleWithService,
            new Dictionary<string, string> { ["ExcludeGeneratedCodeFromCoverage"] = "false" }
        );

        result.AssertNoErrors();
        Verify(!result.SourceContaining("Dependencies").Contains("ExcludeFromCodeCoverage"));
    }

    [VerifyTest]
    public void ExcludeGeneratedCodeFromCoverage_IsCaseInsensitive()
    {
        var result = GeneratorTestHarness.Run(
            ModuleWithService,
            new Dictionary<string, string> { ["ExcludeGeneratedCodeFromCoverage"] = "FALSE" }
        );

        result.AssertNoErrors();
        Verify(!result.SourceContaining("Dependencies").Contains("ExcludeFromCodeCoverage"));
    }

    /// <summary>
    /// RootNamespace is applied to the ApplicationModule that gets generated for a top-level
    /// statement Program.cs; explicitly declared modules keep whatever namespace they are written in.
    /// </summary>
    [VerifyTest]
    public void RootNamespace_NamesTheAutoGeneratedApplicationModule()
    {
        var result = GeneratorTestHarness.Run(
            new Dictionary<string, string>
            {
                ["Program.cs"] = """
                using DependencyModules.Runtime.Attributes;

                System.Console.WriteLine("hello");
                """,
                ["Services.cs"] = """
                namespace TestNamespace;

                public interface IThing;

                [DependencyModules.Runtime.Attributes.SingletonService]
                public class Thing : IThing;
                """,
            },
            new Dictionary<string, string> { ["RootNamespace"] = "ConfiguredRoot" },
            OutputKind.ConsoleApplication
        );

        result.AssertNoErrors();
        Verify(
            result.SourceContaining("ApplicationModule.Module").Contains("namespace ConfiguredRoot")
        );
    }

    [VerifyTest]
    public void AutoGenerateModule_False_SuppressesTheApplicationModule()
    {
        var result = GeneratorTestHarness.Run(
            new Dictionary<string, string>
            {
                ["Program.cs"] = """
                System.Console.WriteLine("hello");
                """,
                ["Services.cs"] = """
                using DependencyModules.Runtime.Attributes;

                namespace TestNamespace;

                public interface IThing;

                [SingletonService]
                public class Thing : IThing;

                [DependencyModule]
                public partial class TestModule;
                """,
            },
            new Dictionary<string, string> { ["DependencyModules_AutoGenerateModule"] = "false" },
            OutputKind.ConsoleApplication
        );

        result.AssertNoErrors();
        Verify(!result.GeneratedSources.Keys.Any(key => key.Contains("ApplicationModule")));
    }

    [VerifyTest]
    [Row("Try", RegistrationType.Try)]
    [Row("Add", RegistrationType.Add)]
    [Row("Replace", RegistrationType.Replace)]
    [Row("TryEnumerable", RegistrationType.TryEnumerable)]
    [Row("RegistrationType.Try", RegistrationType.Try)]
    [Row("", RegistrationType.Add)]
    [Row("nonsense", RegistrationType.Add)]
    public void GetRegistrationType_ParsesKnownValuesAndFallsBackToAdd(
        string input,
        RegistrationType expected
    )
    {
        Verify(BaseSourceGenerator.GetRegistrationType(input) == expected);
    }

    [VerifyTest]
    public void DependencyModulesRegistrationType_ChangesTheDefaultRegistrationMethod()
    {
        var result = GeneratorTestHarness.Run(
            ModuleWithService,
            new Dictionary<string, string> { ["DependencyModules_RegistrationType"] = "Try" }
        );

        result.AssertNoErrors();
        Verify(result.SourceContaining("Dependencies").Contains("TryAdd"));
    }

    [VerifyTest]
    public void GeneratedCodeStyle_DefaultsToAllman()
    {
        var result = GeneratorTestHarness.Run(ModuleWithService);

        result.AssertNoErrors();
        Verify(result.SourceContaining("Dependencies").Contains("services)\n        {"));
    }

    [VerifyTest]
    public void GeneratedCodeStyle_KAndR_PutsTheBraceOnTheOpeningLine()
    {
        var result = GeneratorTestHarness.Run(
            ModuleWithService,
            new Dictionary<string, string> { ["GeneratedCodeStyle"] = "KAndR" }
        );

        result.AssertNoErrors();
        Verify(result.SourceContaining("Dependencies").Contains("services) {"));
        Verify(
            result.SourceContaining("Dependencies").Contains("public partial class TestModule {")
        );
    }

    [VerifyTest]
    public void GeneratedCodeStyle_IsCaseInsensitive()
    {
        var result = GeneratorTestHarness.Run(
            ModuleWithService,
            new Dictionary<string, string> { ["GeneratedCodeStyle"] = "kandr" }
        );

        result.AssertNoErrors();
        Verify(result.SourceContaining("Dependencies").Contains("services) {"));
    }

    /// <summary>
    /// An unrecognized value falls back to the default rather than failing the build, the same
    /// stance DependencyModules_RegistrationType takes.
    /// </summary>
    [VerifyTest]
    public void GeneratedCodeStyle_UnknownValue_FallsBackToAllman()
    {
        var result = GeneratorTestHarness.Run(
            ModuleWithService,
            new Dictionary<string, string> { ["GeneratedCodeStyle"] = "whitesmiths" }
        );

        result.AssertNoErrors();
        Verify(result.SourceContaining("Dependencies").Contains("services)\n        {"));
    }

    private const string ModuleWithService = """
        using DependencyModules.Runtime.Attributes;

        namespace TestNamespace;

        public interface IThing;

        [SingletonService]
        public class Thing : IThing;

        [DependencyModule]
        public partial class TestModule;
        """;
}
